CREATE TABLE app_users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 2) PRIMARY KEY,
  username VARCHAR(64) NOT NULL UNIQUE,
  password_hash VARCHAR(255),
  role VARCHAR(16) NOT NULL CHECK (role IN ('ADMIN', 'USER'))
);

